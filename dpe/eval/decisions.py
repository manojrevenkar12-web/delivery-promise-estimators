"""The management view: what each piece is worth, what it costs to build, and which percentile to serve.

Value comes from the evaluation (each ablation against the full platform, paired by hub-day). Effort comes from
`config/options.yaml` and is an assumption, stated as one. The memo is generated; numbers are never typed in.
"""
from __future__ import annotations

from dpe.config import load
from dpe.eval.report import REPORTS, eur, pct


def served_sweep(est: dict) -> list[str]:
    """The sweep row at the served availability percentile, across stop and travel percentiles."""
    return [f"sweep_q{q}_a{est['availability_quantile']}" for q in (0.5, 0.6, 0.7)]


def select(dev: dict) -> dict:
    """The replay's pick: the cheapest (stop and travel, shows) percentile pair that turns away at most the
    business's share of orders. Compared with what config/estimators.yaml serves."""
    est = load("estimators")
    cap = est["selection"]["max_reject_share"]
    grid = []
    for n, x in dev["designs"].items():
        if n.startswith("sweep_q"):
            q, a = (float(v) for v in n.removeprefix("sweep_q").split("_a"))
            grid.append({"q": q, "a": a, "late_per_day": x["late_per_day"], "reject_share": x["reject_share"],
                         "rejected_per_day": x["rejected_per_day"], "driver_hours_per_day": x["driver_hours_per_day"],
                         "cost_vs_as_found_per_month": x["cost_vs_as_found_per_month"], "ok": x["reject_share"] <= cap})
    grid.sort(key=lambda g: (g["q"], g["a"]))
    ok = [g for g in grid if g["ok"]]
    best = min(ok, key=lambda g: g["cost_vs_as_found_per_month"]) if ok else None
    served = {"q": est["service_quantile"], "a": est["availability_quantile"]}
    return {"max_reject_share": cap, "grid": grid, "pick": best, "served": served,
            "served_is_pick": bool(best and best["q"] == served["q"] and best["a"] == served["a"])}


def decisions(dev: dict, wh: dict | None) -> dict:
    opts, v = load("options"), load("value")
    d = dev["designs"]
    rows = []
    for key, o in opts["estimators"].items():
        a = d.get(o["ablation"])
        if a is None:
            continue
        lo, hi = a["cost_vs_platform_ci"]
        rows.append({"key": key, "area": "Route planning", "label": o["label"], "effort_weeks": o["effort_weeks"],
                     "value_per_month": a["cost_vs_platform_per_month"], "value_ci": [lo, hi],
                     "late_avoided_per_day": a["late_vs_platform_per_day"], "clear": lo > 0 or hi < 0,
                     "reject_share_without": a["reject_share"]})
    if wh:
        w = wh["designs"]
        for key, o in opts["warehouse"].items():
            a = w.get(o["ablation"])
            if a is None:
                continue
            val = a["cost_per_month"] - w["platform"]["cost_per_month"]
            rows.append({"key": key, "area": "Warehouse", "label": o["label"], "effort_weeks": o["effort_weeks"],
                         "value_per_month": val, "value_ci": None, "late_avoided_per_day": None,
                         "minutes_per_order_saved": a["minutes_per_order"] - w["platform"]["minutes_per_order"],
                         "clear": None, "one_off_hours": o.get("one_off_hours")})
    for r in rows:
        r["value_per_effort_week"] = r["value_per_month"] / r["effort_weeks"]
    rows.sort(key=lambda r: -r["value_per_effort_week"])
    sel = select(dev)
    sens = []
    for late_cost in opts["late_cost_sensitivity"]:
        costs = {(g["q"], g["a"]): (g["rejected_per_day"] * v["margin_per_order_eur"] + g["late_per_day"] * late_cost
                                    + g["driver_hours_per_day"] * v["driver_hour_eur"]) * v["days_per_month"]
                 for g in sel["grid"] if g["ok"]}
        if not costs:
            continue
        q, a = min(costs, key=costs.get)
        sens.append({"late_cost_eur": late_cost, "best_quantile": q, "best_availability": a,
                     "late_per_day": next(g["late_per_day"] for g in sel["grid"] if (g["q"], g["a"]) == (q, a))})
    return {"options": rows, "sensitivity": sens, "selection": sel}


def memo(dev: dict, dec: dict, heldout_fails: list[str] | None) -> str:
    d = dev["designs"]
    p, a = d["platform"], d["as_found"]
    v = load("value")
    lines = [
        "# Decision memo: estimators for route planning and picking",
        "",
        "_Generated by `python -m dpe.eval.cli evaluate` from the development hubs. Do not edit by hand._",
        "",
        "## In short",
        "",
        f"On the same simulated orders, streets and absences, the platform's estimators cut late deliveries from "
        f"{a['late_per_day']:.0f} to {p['late_per_day']:.0f} a day per hub "
        f"({pct(a['late_share'])} to {pct(p['late_share'])} of accepted orders). They do it partly by turning more "
        f"orders away when the hub is full ({pct(a['reject_share'])} to {pct(p['reject_share'])}): the planner no "
        f"longer accepts orders it cannot deliver on time. Net of driver hours, the hub "
        f"{'saves' if p['cost_vs_as_found_per_month'] < 0 else 'costs an extra'} "
        f"{eur(abs(p['cost_vs_as_found_per_month']))} a month against today (95% interval of the change "
        f"{eur(p['cost_vs_as_found_ci'][0])} to {eur(p['cost_vs_as_found_ci'][1])}), at "
        f"€{v['late_cost_eur']:.0f} per late delivery and €{v['margin_per_order_eur']:.1f} per order turned away.",
        "",
    ]
    if heldout_fails is not None:
        lines += ["On the held-out hubs the gate " + ("passed." if not heldout_fails else
                                                      "did not pass: " + "; ".join(heldout_fails) + "."), ""]
    lines += ["## What to build first", "",
              "Value is each piece's paired saving against the full platform without it; effort is this team's "
              "estimate in `config/options.yaml`.", "",
              "| Rank | Area | Option | Value per month | Late deliveries avoided per day | Effort (weeks) | Clear of zero |",
              "|---:|---|---|---:|---:|---:|---|"]
    for i, r in enumerate(dec["options"], 1):
        ci = f" ({eur(r['value_ci'][0])} to {eur(r['value_ci'][1])})" if r["value_ci"] else ""
        late = "–" if r["late_avoided_per_day"] is None else f"{r['late_avoided_per_day']:.1f}"
        clear = "–" if r["clear"] is None else ("yes" if r["clear"] else "no")
        lines.append(f"| {i} | {r['area']} | {r['label']} | {eur(r['value_per_month'])}{ci} | {late} | "
                     f"{r['effort_weeks']} | {clear} |")
    sel = dec["selection"]
    neg = [r for r in dec["options"] if r["value_per_month"] < 0 and r.get("reject_share_without", 0) > sel["max_reject_share"]]
    if neg:
        lines += ["", "Pieces with a negative value save money only by breaking the service level: without them the hub "
                  "turns away " + ", ".join(f"{pct(r['reject_share_without'])} ({r['label'].lower()})" for r in neg)
                  + f" of orders, over the {pct(sel['max_reject_share'], 0)} the business allows. Their value is "
                  "keeping that level at the least cost."]
    lines += ["", "## How the percentiles were chosen", "",
              f"Every pair of percentiles was replayed on the development hubs. The pick is the cheapest pair that turns "
              f"away at most {pct(sel['max_reject_share'], 0)} of orders, a service level the business sets.", "",
              "| Stops and travel | Shows | Late per day | Turned away | Cost against as found |", "|---:|---:|---:|---:|---:|"]
    for g in sel["grid"]:
        mark = " **(pick)**" if sel["pick"] and g["q"] == sel["pick"]["q"] and g["a"] == sel["pick"]["a"] else ""
        lines.append(f"| {round(g['q'] * 100)}th | {round(g['a'] * 100)}th | {g['late_per_day']:.1f} | "
                     f"{pct(g['reject_share'])}{'' if g['ok'] else ' (over)'} | {eur(g['cost_vs_as_found_per_month'])}{mark} |")
    lines += ["", "Served now: the " + f"{round(sel['served']['q'] * 100)}th and {round(sel['served']['a'] * 100)}th percentiles"
              + (", the replay's pick." if sel["served_is_pick"] else ", which is not the replay's pick: update config/estimators.yaml.")]
    lines += ["", "## If a late delivery is worth more", "",
              f"The pick above prices a late delivery at €{v['late_cost_eur']:.0f}. At other prices, still turning away at most "
              f"{pct(sel['max_reject_share'], 0)} of orders, the cheapest pair is:", "",
              "| A late delivery costs | Stops and travel | Shows | Late per day |", "|---:|---:|---:|---:|"]
    for s_ in dec["sensitivity"]:
        lines.append(f"| €{s_['late_cost_eur']} | {round(s_['best_quantile'] * 100)}th | {round(s_['best_availability'] * 100)}th | "
                     f"{s_['late_per_day']:.1f} |")
    lines += ["", "## What we watch", "",
              f"- **Coverage.** Stops under the served estimate: {pct(p['stop_coverage'], 0)} (target "
              f"{pct(p['stop_quantile'], 0)}); legs: {pct(p['travel_coverage'], 0)} (target {pct(p['travel_quantile'], 0)}). "
              "Two days well below target trigger an early retrain.",
              f"- **Retraining.** {p['retrains']} challengers judged, {p['promoted']} promoted, "
              f"{p['drift_retrains']} of them after a drift alarm.",
              f"- **Rostering.** {p['short_shifts_per_week']:.1f} shifts a week two or more drivers short of plan "
              f"(as found: {a['short_shifts_per_week']:.1f}).",
              "", "## What this does not show", "",
              "- The hubs, customers, streets and drivers are simulated; the planner is a plain stand-in for the "
              "real one. The ranking of options is the result to take forward, not the euro amounts.",
              "- Effort figures are estimates, not measurements.", ""]
    return "\n".join(lines)


def write_memo(text: str) -> None:
    (REPORTS / "decision_memo.md").write_text(text)
